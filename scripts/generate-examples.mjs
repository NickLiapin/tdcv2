/**
 * Turn `data/examples/*.tdc` into a constant in each of the five implementations.
 *
 * `tdcv2 init` writes these files into a user's folder, so every implementation
 * needs the text. Shipping them as DATA would mean wiring five different
 * packaging layouts — `data/examples` in the npm tarball, `examples_data` inside
 * the Python package, resources in the jar, and so on — and an install that lost
 * the folder would silently lose the examples with no way to notice.
 *
 * They are 5 KB of text. Embedding them is smaller than the plumbing, works
 * whatever the install looks like, and `--check` in the gate is what keeps the
 * five copies from drifting away from the source at the repo root.
 *
 *   node scripts/generate-examples.mjs           # write
 *   node scripts/generate-examples.mjs --check   # fail if any copy is stale
 */

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '..');
const source = join(repo, 'data', 'examples');

const examples = readdirSync(source)
  .filter((n) => n.endsWith('.tdc'))
  .sort()
  .map((name) => ({ name, body: readFileSync(join(source, name), 'utf8') }));

if (examples.length === 0) {
  console.error('generate-examples: no .tdc files at ' + source);
  process.exit(1);
}

const BANNER = 'Generated by scripts/generate-examples.mjs from data/examples — do not edit.';

/** A body as a source-language string literal, newlines and quotes intact. */
const js = (s) => JSON.stringify(s);
const py = (s) => JSON.stringify(s); // Python accepts JSON string escapes
const rs = (s) => JSON.stringify(s);
const cs = (s) => JSON.stringify(s);

const targets = [
  {
    path: 'typescript/src/cli/examples.generated.ts',
    render: () =>
      `/** ${BANNER} */\n\n` +
      `export const EXAMPLES: readonly { readonly name: string; readonly body: string }[] = [\n` +
      examples.map((e) => `  { name: ${js(e.name)}, body: ${js(e.body)} },\n`).join('') +
      `];\n`,
  },
  {
    path: 'python/src/tdcv2/cli/examples_generated.py',
    render: () =>
      `"""${BANNER}"""\n\n# ruff: noqa\n# The bodies are the examples verbatim; wrapping them would change what a\n# user's file says.\n\n` +
      `EXAMPLES: list[tuple[str, str]] = [\n` +
      examples.map((e) => `    (${py(e.name)}, ${py(e.body)}),\n`).join('') +
      `]\n`,
  },
  {
    path: 'rust/src/cli/examples_generated.rs',
    render: () =>
      `//! ${BANNER}\n\n` +
      `pub const EXAMPLES: &[(&str, &str)] = &[\n` +
      examples.map((e) => `    (${rs(e.name)}, ${rs(e.body)}),\n`).join('') +
      `];\n`,
  },
  {
    path: 'java/src/main/java/io/github/nickliapin/tdc/cli/ExamplesGenerated.java',
    render: () =>
      `package io.github.nickliapin.tdc.cli;\n\n` +
      `import java.util.List;\n\n` +
      `/** ${BANNER} */\n` +
      `final class ExamplesGenerated {\n` +
      `  private ExamplesGenerated() {}\n\n` +
      `  static final List<String[]> EXAMPLES = List.of(\n` +
      examples
        .map((e, i) => `      new String[] {${js(e.name)}, ${js(e.body)}}${i < examples.length - 1 ? ',' : ''}\n`)
        .join('') +
      `  );\n}\n`,
  },
  {
    path: 'csharp/Tdcv2/Cli/ExamplesGenerated.cs',
    render: () =>
      `// ${BANNER}\n\nnamespace Tdcv2.Cli;\n\n` +
      `internal static class ExamplesGenerated\n{\n` +
      `    internal static readonly (string Name, string Body)[] Examples =\n    {\n` +
      examples.map((e) => `        (${cs(e.name)}, ${cs(e.body)}),\n`).join('') +
      `    };\n}\n`,
  },
];

const check = process.argv.includes('--check');
let stale = 0;
for (const t of targets) {
  const full = join(repo, t.path);
  const wanted = t.render();
  let current = '';
  try {
    current = readFileSync(full, 'utf8');
  } catch {
    current = '';
  }
  if (current === wanted) continue;
  if (check) {
    console.error(`generate-examples: ${t.path} is out of date`);
    stale++;
  } else {
    writeFileSync(full, wanted, 'utf8');
    console.error(`generate-examples: wrote ${t.path}`);
  }
}

if (check) {
  if (stale > 0) {
    console.error(`\nRun \`node scripts/generate-examples.mjs\` and commit the result.`);
    process.exit(1);
  }
  console.log(`${examples.length} worked examples match all five implementations`);
}
