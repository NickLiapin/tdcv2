#!/usr/bin/env node
/**
 * Put the starter data packs inside the crate, just long enough to build it.
 *
 * A published crate is a tarball with nothing above it. The Rust implementation
 * finds packs by walking up from `CARGO_MANIFEST_DIR` looking for `data/packs`,
 * which works in a checkout and cannot work in `~/.cargo/registry` — so a crate
 * published as-is answers every `type="template"` with "no data packs found".
 * Verified by unpacking the crate outside the repository and running one.
 *
 * The packs live once, at the repository root, shared by all five
 * implementations. So they are copied in before packaging and removed after,
 * exactly as `typescript/scripts/bundle-packs.mjs` does for npm — a stale
 * duplicate left behind inside the crate would shadow the real one and be
 * silently out of date.
 *
 * Unlike npm, Cargo has no `prepack` hook, so this runs by hand:
 *
 *   node scripts/bundle-packs.mjs add      # before `cargo package` / `cargo publish`
 *   node scripts/bundle-packs.mjs remove   # after
 *
 * `add` also writes `src/packs/bundled_files.rs`, a table of `include_str!`
 * entries. That is what actually embeds the data in the binary: the .txt files
 * are read at COMPILE time, so the built program needs no files beside it at
 * all — which is the only shape that works for `cargo install tdcv2`.
 */

import { cpSync, existsSync, mkdirSync, readdirSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, '..', '..', 'data', 'packs');
const target = resolve(here, '..', 'src', 'packs', 'bundled');
const table = resolve(here, '..', 'src', 'packs', 'bundled_files.rs');

/**
 * What ships inside the crate: enough to run the documentation's first example
 * and nothing more. Everything else is a download away — `tdcv2 pack add ru
 * france` — from the registry every implementation reads.
 *
 * The same three npm, the wheel and the jar carry, deliberately: an install that
 * behaves differently depending on which ecosystem it came from is the bug the
 * shared fixtures exist to prevent, and it would be worst in the very first
 * minute of someone's first try.
 */
const STARTER = ['common', 'en', 'countries/usa'];

/** The stub that a checkout carries: no embedded data, so the disk is used. */
const EMPTY_TABLE = `//! Generated by \`scripts/bundle-packs.mjs\`. Do not edit.
//!
//! Empty in a checkout: there the packs are on disk at the repository root, and
//! reading them from there is what keeps this implementation and the other four
//! looking at the very same bytes. \`bundle-packs.mjs add\` fills this in for the
//! published crate, where there is no repository to walk up to.

/// Every bundled pack file: its address-bearing path, and its contents.
pub const FILES: &[(&str, &str)] = &[];
`;

function walk(dir, prefix, out) {
  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) =>
    a.name < b.name ? -1 : 1,
  )) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(full, prefix, out);
    } else if (entry.name.endsWith('.txt')) {
      out.push(relative(prefix, full).split(sep).join('/'));
    }
  }
  return out;
}

const mode = process.argv[2];

if (mode === 'add') {
  rmSync(target, { recursive: true, force: true });
  const staging = `${target}.staging`;
  rmSync(staging, { recursive: true, force: true });
  mkdirSync(staging, { recursive: true });
  for (const pack of STARTER) {
    const from = join(source, ...pack.split('/'));
    if (!existsSync(from)) {
      console.error(`bundle-packs: ${pack} is not in ${source}`);
      process.exit(1);
    }
    cpSync(from, join(staging, ...pack.split('/')), { recursive: true });
  }
  // Built beside, then renamed: a concurrent build must never see it half full.
  renameSync(staging, target);

  const files = walk(target, target, []);
  const rows = files
    .map((f) => `    ("${f}", include_str!("bundled/${f}")),`)
    .join('\n');
  writeFileSync(
    table,
    `//! Generated by \`scripts/bundle-packs.mjs\`. Do not edit.
//!
//! The starter packs, read at COMPILE time so the built program needs no files
//! beside it — the only shape that works for a crate installed from the
//! registry, where there is no repository above it to walk up to.

/// Every bundled pack file: its address-bearing path, and its contents.
pub const FILES: &[(&str, &str)] = &[
${rows}
];
`,
  );
  console.log(`bundle-packs: embedded ${String(files.length)} files from ${STARTER.join(', ')}`);
} else if (mode === 'remove') {
  if (existsSync(target)) {
    const doomed = `${target}.removing`;
    rmSync(doomed, { recursive: true, force: true });
    renameSync(target, doomed);
    rmSync(doomed, { recursive: true, force: true });
  }
  writeFileSync(table, EMPTY_TABLE);
  console.log('bundle-packs: removed the temporary copy');
} else {
  console.error('usage: bundle-packs.mjs add|remove');
  process.exit(2);
}
